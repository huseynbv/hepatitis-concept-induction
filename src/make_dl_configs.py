"""Writes one .conf per experiment in grid.json; examples are the training patients only.
"""
from pathlib import Path
import argparse
import json

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PREFIX = "http://example.org/hepatitis.owl#"

LANGUAGES = {
    "EL":   dict(useNegation=False, useAllConstructor=False, useCardinalityRestrictions=False,
                 useNumericDatatypes=False),
    "ALC":  dict(useNegation=True, useAllConstructor=True, useCardinalityRestrictions=False,
                 useNumericDatatypes=False),
    "ALCQ": dict(useNegation=True, useAllConstructor=True, useCardinalityRestrictions=True,
                 useNumericDatatypes=False),
    "ALCD": dict(useNegation=True, useAllConstructor=True, useCardinalityRestrictions=False,
                 useNumericDatatypes=True),
    "FULL": dict(useNegation=True, useAllConstructor=True, useCardinalityRestrictions=True,
                 useNumericDatatypes=True),
}


def fmt_examples(ids):
    lines = ",\n".join(f'    "hep:patient_{i}"' for i in ids)
    return "{\n" + lines + "\n}"


def render(exp, pos, neg, out_dir):
    kb_path = Path("..") / ".." / "ontology" / exp["kb"]
    lang = LANGUAGES[exp["language"]]
    op_lines = "\n".join(f"op.{k} = {str(v).lower()}" for k, v in lang.items())
    if lang["useCardinalityRestrictions"]:
        op_lines += "\nop.cardinalityLimit = 5"
    op_lines += "\nop.useDataHasValueConstructor = false"
    op_lines += "\nop.useBooleanDatatypes = false"
    op_lines += "\nop.useStringDatatypes = false"

    alg = exp["algorithm"]
    alg_lines = [f'alg.type = "{alg}"',
                 f"alg.maxExecutionTimeInSeconds = {exp['time']}",
                 f'alg.startClass = "hep:{exp["start_class"]}"',
                 "alg.operator = op",
                 "alg.writeSearchTree = false"]
    if alg == "celoe":
        alg_lines += [f"alg.maxDepth = {exp['max_depth']}",
                      f"alg.noisePercentage = {exp['noise']}",
                      "alg.maxNrOfResults = 10",
                      "alg.heuristic = h"]
        heuristic = ('h.type = "celoe_heuristic"\n'
                     f"h.expansionPenaltyFactor = {exp['expansion_penalty']}")
    else:  # ocel
        alg_lines += [f"alg.noisePercentage = {exp['noise']}"]
        heuristic = "// OCEL uses its own built-in heuristic"
    acc = (f'accMethod.type = "{exp["accuracy_method"]}"\n'
           "lp.accuracyMethod = accMethod")

    text = f"""// generated by src/make_dl_configs.py
// Experiment: {exp['id']}  (group: {exp.get('group', '-')})
// KB: {exp['kb']} | algorithm: {alg} | language: {exp['language']} | time: {exp['time']}s
// max_depth: {exp['max_depth']} | noise: {exp['noise']}% | expansion penalty: {exp['expansion_penalty']}
// accuracy method: {exp['accuracy_method']} | P = {len(pos)}, N = {len(neg)} (training split)

prefixes = [ ("hep","{PREFIX}") ]

// knowledge source
ks.type = "OWL File"
ks.fileName = "{kb_path.as_posix()}"

// reasoner
reasoner.type = "closed world reasoner"
reasoner.sources = {{ ks }}

// learning problem
lp.type = "posNegStandard"
{acc}
lp.positiveExamples = {fmt_examples(pos)}
lp.negativeExamples = {fmt_examples(neg)}

// operator ({exp['language']})
op.type = "rho"
{op_lines}

// heuristic
{heuristic}

// learning algorithm
{chr(10).join(alg_lines)}
"""
    path = out_dir / f"{exp['id']}.conf"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--grid", type=Path, default=ROOT / "configs" / "experiments" / "grid.json")
    ap.add_argument("--train", type=Path, default=ROOT / "configs" / "folds" / "train.csv")
    ap.add_argument("--out", type=Path, default=ROOT / "configs" / "dl-learner")
    args = ap.parse_args()

    grid = json.loads(args.grid.read_text())
    train = pd.read_csv(args.train)
    pos = sorted(train.loc[train.target == 1, "patient_id"])
    neg = sorted(train.loc[train.target == 0, "patient_id"])
    assert len(pos) == 235 and len(neg) == 165

    args.out.mkdir(parents=True, exist_ok=True)
    written = []
    for exp in grid["experiments"]:
        full = {**grid["defaults"], **exp}
        assert full["language"] in LANGUAGES, full["language"]
        assert (ROOT / "ontology" / full["kb"]).exists(), f"missing KB {full['kb']}"
        written.append(render(full, pos, neg, args.out))
    print(f"{len(written)} conf files written to {args.out}")
    for p in written:
        print("  ", p.name)


if __name__ == "__main__":
    main()
