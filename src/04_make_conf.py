"""Step 4 - Generate DL-Learner .conf files (one per fold) for a named experiment setting.

A .conf file wires together DL-Learner's components:
  ks   (knowledge source)  : which .owl file to load
  reasoner                 : how instance checks are answered. "closed world reasoner"
                             (CWA, fast, materialises the ABox) vs "OWL API" + HermiT (OWA)
  lp   (learning problem)  : posNegStandard = P and N example sets (training fold only!)
  op   (refinement operator): rho - defines the HYPOTHESIS LANGUAGE, i.e. which
                             constructors (¬, ∀, ⊔, ≥n, datatype ≥/≤) may be used
  alg  (learning algorithm): CELOE - heuristic search over the refinement tree, favouring
                             short, accurate concepts

Usage:  python src/04_make_conf.py <setting> [--folds 0 1 2 3 4]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NS = "http://example.org/hepatitis#"

# Each setting = overrides of the base configuration. Experiments vary these.
BASE = {
    "ontology": "hepatitis_datatype.owl",
    "reasoner": "closed world reasoner",
    "runtime": 60,              # alg.maxExecutionTimeInSeconds
    "noise": 30,                # CELOE: concepts covering < (100-noise)% of P are not refined
    "penalty": 0.1,             # celoe_heuristic.expansionPenaltyFactor: score lost per length unit
    "op": {
        "useNumericDatatypes": "true",
        "useNegation": "true",
        "useAllConstructor": "true",
        "useCardinalityRestrictions": "true",
        "useHasValueConstructor": "false",
    },
}
RESTRICTED = {"useNegation": "false", "useAllConstructor": "false",
              "useCardinalityRestrictions": "false"}
SETTINGS = {
    "base": {},
    # E1 hypothesis language: drop ¬, ∀ and ≤n/≥n (keep ⊓, ⊔, ∃, numeric ranges)
    "lang_restricted": {"op": RESTRICTED},
    # E2 runtime (run with --jobs 1 so every fold gets a full CPU)
    "rt10": {"runtime": 10}, "rt60": {"runtime": 60}, "rt180": {"runtime": 180},
    # E3 encoding of ordinal bins: one atomic class per bin instead of integer data properties
    "enc_classes": {"ontology": "hepatitis_classes.owl"},
    # E4 noise tolerance
    "noise10": {"noise": 10}, "noise50": {"noise": 50},
    # E5 heuristic: weaker length penalty -> longer concepts allowed
    "penalty002": {"penalty": 0.02}, "penalty001": {"penalty": 0.01},
    # E6 open world: OWL API reasoner with HermiT instead of the closed world reasoner
    "owa_hermit": {"reasoner": "hermit"},
    # E7 leakage demonstration: ontology including the interferon therapy table
    "leak_therapy": {"ontology": "hepatitis_datatype_therapy.owl"},
}


def write_conf(setting: str, cfg: dict, fold: dict, out_dir: Path) -> Path:
    def ex(lst):
        return ",\n  ".join(f'"kb:{i}"' for i in lst)

    op_lines = "\n".join(f"op.{k} = {v}" for k, v in cfg["op"].items())
    reasoner = (f'reasoner.type = "closed world reasoner"' if cfg["reasoner"] == "closed world reasoner"
                else 'reasoner.type = "OWL API Reasoner"\nreasoner.reasonerImplementation = "hermit"')
    text = f"""// setting={setting} fold={fold['fold']}  (generated by src/04_make_conf.py)
// P = Hepatitis B, N = Hepatitis C  (training part of the fold only)
prefixes = [ ("kb","{NS}") ]

ks.type = "OWL File"
ks.fileName = "{(ROOT / 'ontology' / cfg['ontology']).as_posix()}"

{reasoner}
reasoner.sources = {{ ks }}

lp.type = "posNegStandard"
lp.positiveExamples = {{
  {ex(fold['train_pos'])}
}}
lp.negativeExamples = {{
  {ex(fold['train_neg'])}
}}
lp.reasoner = reasoner

op.type = "rho"
op.reasoner = reasoner
{op_lines}

h.type = "celoe_heuristic"
h.expansionPenaltyFactor = {cfg['penalty']}

alg.type = "celoe"
alg.reasoner = reasoner
alg.learningProblem = lp
alg.operator = op
alg.heuristic = h
alg.maxExecutionTimeInSeconds = {cfg['runtime']}
alg.noisePercentage = {cfg['noise']}
alg.maxNrOfResults = 10
"""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"fold{fold['fold']}.conf"
    path.write_text(text)
    return path


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("setting", choices=SETTINGS)
    ap.add_argument("--folds", type=int, nargs="*", default=[0, 1, 2, 3, 4])
    a = ap.parse_args()
    cfg = {**BASE, **SETTINGS[a.setting], "op": {**BASE["op"], **SETTINGS[a.setting].get("op", {})}}
    folds = json.loads((ROOT / "data" / "folds.json").read_text())
    for k in a.folds:
        print("wrote", write_conf(a.setting, cfg, folds[k], ROOT / "conf" / a.setting).relative_to(ROOT))
